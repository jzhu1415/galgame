import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import ts from 'typescript'
import { tsModuleUrl, moduleUrl } from './ts-module.mjs'

// Extract pure local data without mounting a controller, reading saves or shipping
// every chapter to the campaign bundle. The output contains totals only.
async function localData(file, name) {
  const source = readFileSync(file, 'utf8')
  const ast = ts.createSourceFile(file, source, ts.ScriptTarget.ES2022, true)
  let expression
  function visit(node) {
    if (ts.isVariableDeclaration(node) && node.name.getText(ast) === name) expression = node.initializer.getText(ast)
    ts.forEachChild(node, visit)
  }
  visit(ast)
  if (!expression) throw new Error(`${file}: missing ${name}`)
  return (await import(moduleUrl(ts.transpileModule(`export default ${expression}`, { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText))).default
}
const load = name => import(tsModuleUrl(`src/${name}.ts`))
const [{ story }, { theatreStory }, { gildedStory }, { romanceStory }, { finaleStories }, { iceNodeIds }, thirdVisuals, fourthVisuals, coastalVisuals, finaleArtwork] = await Promise.all([
  load('story'), load('chapter-three-story'), load('chapter-four-story'), load('romance-dlc-story'), load('finale-story'), load('chapter-two-progress'), load('chapter-three-visuals'), load('chapter-four-visuals'), load('romance-dlc-visuals'), load('finale-artwork'),
])
const [iceCopy, fragments, iceArt, finalePortraits] = await Promise.all([
  localData('src/chapter-two.ts', 'copy'), localData('src/chapter-two.ts', 'fragmentStories'), localData('src/chapter-two.ts', 'artByPhase'), localData('src/finale.ts', 'finalePortraits'),
])
const images = new Set()
function addImage(value) {
  const path = value.startsWith('/images/') ? value.slice(1) : `images/${value}.webp`
  if (!existsSync(`public/${path}`)) throw new Error(`Missing active artwork: ${path}`)
  images.add(path)
}
Object.values(story).forEach(node => addImage(node.image))
Object.values(iceArt).flat().forEach(addImage)
Object.values(fragments.zh).flatMap(fragment => fragment.art).forEach(addImage)
addImage('finale-banana-cat')
for (const [id, node] of Object.entries(theatreStory)) {
  for (let line = 0; line < Math.max(node.lines.length, 1); line++) {
    const visual = thirdVisuals.chapterThreeVisual(id, line)
    addImage(visual.background)
    if (visual.showCharacter) addImage(thirdVisuals.naifenExpressions[visual.expression].image)
  }
}
// Includes the fourth chapter's in-game art viewer and puzzle/journal paintings.
Object.values(fourthVisuals.gildedVisuals).forEach(visual => addImage(visual.file))
for (const [id, node] of Object.entries(romanceStory)) {
  addImage(coastalVisuals.romanceEnvironment(id))
  node.lines.forEach((_, line) => addImage(coastalVisuals.romanceVisual(id, line).image))
}
for (const [id, node] of Object.entries(finaleStories[5])) {
  node.lines.forEach((_, line) => addImage(finaleArtwork.finaleArtwork({ chapter: 5, node: id, line }).src))
}
Object.values(finalePortraits).forEach(addImage)

const chineseCount = text => [...text].filter(character => /\p{Script=Han}/u.test(character)).length
function section(id, nodes, texts) {
  return { id, storyNodes: nodes, dialogueLines: texts.length, chineseCharacters: texts.reduce((sum, text) => sum + chineseCount(text), 0) }
}
const iceTexts = [
  ...['hospital', 'threshold', 'core', 'ending'].flatMap(phase => iceCopy.zh[phase].map(line => line[1])),
  ...Object.values(fragments.zh).flatMap(fragment => fragment.lines.map(line => line[1])),
  ...Object.values(iceCopy.zh.approachLines), ...Object.values(iceCopy.zh.responseLines),
]
const sections = [['chapter-1', story], ['chapter-3', theatreStory], ['chapter-4', gildedStory], ['chapter-5', finaleStories[5]], ['coastal-dlc', romanceStory]].map(([id, data]) => section(id, Object.keys(data).length, Object.values(data).flatMap(node => node.lines.flatMap(line => [line.text.zh, ...(line.blanketText ? [line.blanketText.zh] : [])]))))
sections.splice(1, 0, section('chapter-2', iceNodeIds.length, iceTexts))
const totals = sections.reduce((sum, item) => ({ storyNodes: sum.storyNodes + item.storyNodes, dialogueLines: sum.dialogueLines + item.dialogueLines, chineseCharacters: sum.chineseCharacters + item.chineseCharacters }), { storyNodes: 0, dialogueLines: 0, chineseCharacters: 0 })
totals.visualAssets = images.size
const outputs = {
  'src/game-statistics.ts': `// Generated by scripts/generate-game-statistics.mjs. Do not edit totals by hand.\n// Five main chapters + coastal DLC; Chinese dialogue includes conditional variants.\nexport const gameStatistics = ${JSON.stringify(totals, null, 2)} as const\n`,
  'docs/game-statistics.json': JSON.stringify({ scope: 'Five main chapters + coastal DLC; merged finale counted once', definitions: { chineseCharacters: 'Han characters in Chinese dialogue, including conditional variants; excludes punctuation, English translations, menus and promo copy', storyNodes: 'Authored story nodes; chapter two uses the shared map node IDs, including investigation and route nodes', dialogueLines: 'Authored dialogue/narration entries, including conditional variants; each bilingual pair counts once', visualAssets: 'Unique existing WebP paths used by story frames, portraits, puzzle, journal and in-game art viewers; shared art counts once; excludes reference PNGs, retired files, procedural 3D geometry and video frames' }, totals, sections, images: [...images].sort() }, null, 2) + '\n',
}
const check = process.argv.includes('--check')
for (const [file, output] of Object.entries(outputs)) {
  const current = existsSync(file) ? readFileSync(file, 'utf8') : ''
  if (check && current !== output) throw new Error(`Statistics are stale: run node scripts/generate-game-statistics.mjs (${file})`)
  if (!check && current !== output) writeFileSync(file, output)
}
console.log(`Whole-game statistics ${check ? 'verified' : 'generated'}: ${JSON.stringify(totals)}`)
